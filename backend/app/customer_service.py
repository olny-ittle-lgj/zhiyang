def _normalise(value: str) -> str:
    return re.sub(r"\s+", " ", value.casefold()).strip()


def _terms(value: str) -> set[str]:
    normalised = _normalise(value)
    terms = set(re.findall(r"[a-z0-9_]{2,}", normalised))
    compact = re.sub(r"\s+", "", normalised)
    for segment in re.findall(r"[\u4e00-\u9fff]{2,}", compact):
        terms.update(segment[index:index + 2] for index in range(len(segment) - 1))
    return terms


def _score(article: dict[str, Any], question: str) -> int:
    normalised_question = _normalise(question)
    question_terms = _terms(question)
    score = 0
    title = _normalise(article["title"])
    summary = _normalise(article["summary"])
    searchable = _normalise(" ".join([
        article["title"],
        article["summary"],
        article["answer"],
        " ".join(article["keywords"]),
    ]))
    if normalised_question and normalised_question in title:
        score += 18
    if normalised_question and normalised_question in summary:
        score += 10
    for term in question_terms:
        if term in title:
            score += 5
        elif term in summary:
            score += 3
        elif term in searchable:
            score += 1
    return score


def _public_article(article: dict[str, Any]) -> dict[str, Any]:
    public = deepcopy(article)
    public.pop("keywords", None)
    return public


